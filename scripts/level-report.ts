// Verifies all 90 levels and writes docs/LEVEL_REPORT.md: solution, solution length, star thresholds and pass/fail for each.
// The checks are the same ones the test suite runs; nothing here is assumed.
// Run: npx tsx scripts/level-report.ts
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { applyMove, initialState, losingSequence, replay, solve, starsFor, traceState, validateLevel, winningSequences } from '../src/game/engine';
import { chapters } from '../src/game/chapters';
import { levels } from '../src/game/levels';
import { Level } from '../src/game/types';

const modifierNames: Partial<Record<Level['mechanics'][number], string>> = {
  turn: 'turning cannon', twin: 'twin cannons', triple: 'triple cannons', totem: 'rootbound totems', ride: 'cannon on a cluster', totems: 'two totems',
  jam: 'jammed cluster', seal: 'solar seals',
  floe: 'drift ice', stop: 'floe stoppers', devourer: 'Light Devourer', splitter: 'prisms', portal: 'wormholes',
};

/** Plays taps from the opening board: the shards earned, or 0 for a loss. */
function play(level: Level, taps: string[]) {
  let s = initialState(level);
  for (let k = 0; k < taps.length; k++) {
    s = applyMove(level, s, taps[k]!);
    if (traceState(level, s).won) return starsFor(level, k + 1);
    if (s.absorbed || k + 1 >= level.maxMoves) return 0;
  }
  return 0;
}

const rows: string[] = [];
let passed = 0;
const started = Date.now();
for (const level of levels) {
  const problems = validateLevel(level);
  const optimal = solve(level, initialState(level));
  const wins = winningSequences(level, level.maxMoves);
  const tier = (from: number, to: number) => [...wins.keys()].find(k => k >= from && k <= to);
  const three = tier(level.par, level.par), two = tier(level.par + 1, level.twoStar), one = tier(level.twoStar + 1, level.maxMoves);
  const lose = losingSequence(level);
  if (three === undefined || play(level, wins.get(three)!) !== 3) problems.push('no 3-shard win');
  if (two === undefined || play(level, wins.get(two)!) !== 2) problems.push('no 2-shard win');
  if (one === undefined || play(level, wins.get(one)!) !== 1) problems.push('no 1-shard win');
  if (!lose || play(level, lose.taps) !== 0) problems.push('cannot be lost');
  const end = traceState(level, replay(level, level.solutionMoves));
  if (!end.won || end.activated.length !== level.targets.length) problems.push('solution does not light every crystal');
  if (!optimal || optimal.length !== level.par) problems.push('par is not the optimum');
  const ok = problems.length === 0;
  if (ok) passed++;
  const mods = level.mechanics.map(m => modifierNames[m]).filter(Boolean).join(', ') || 'mirrors';
  rows.push(`| ${level.id} | ${chapters[level.chapter]!.world} ${level.index} | ${level.title} | ${mods} | ${level.size}x${level.size} | ${level.emitters.length} | `
    + `\`${level.solutionMoves.join(' ')}\` | ${level.par} | ≤ ${level.par} | ≤ ${level.twoStar} | ≤ ${level.maxMoves} | ${three}/${two}/${one} | `
    + `${lose ? (lose.devoured ? 'feeds the Devourer' : 'out of moves') : '-'} | ${ok ? 'PASS' : `FAIL: ${problems.join('; ')}`} |`);
}

const doc = `# Mirror Maze: level verification report

Generated by \`npx tsx scripts/level-report.ts\` on ${new Date().toISOString().slice(0, 10)}. Every value below was computed from the
level data with the game's own rules engine; nothing is entered by hand.

**Result: ${passed} of ${levels.length} levels pass.**

## Scoring contract

One rule for every level, derived from the solver's optimal move count (par):

| Shards | Condition |
| --- | --- |
| 3 | Won in at most **par** moves (par is the true shortest solution, found by breadth-first search) |
| 2 | Won in at most **par + 2** moves |
| 1 | Won within the level's move limit (**par + 3** to **par + 6**, tighter on expert levels) |
| 0 | Out of moves without lighting every crystal, or light fed to the Light Devourer |

For each level the report proves all four outcomes with real tap sequences played under the actual rules (totem turns,
floe glides, seal order, the Devourer): the "Proven wins" column gives the move counts of the 3-, 2- and 1-shard
wins that were played, and "Can be lost" how a loss happens. A win never needs a perfect score.

## Checks per level

* Board is valid: pieces in bounds, no overlaps, unique ids, seals numbered 1, 2, 3 ..., rootbound
  clusters are connected cells with a cell-centre or cell-corner pivot and nothing they cannot carry, totems stand on their
  own cells, floe tracks are straight lines of open ice that cross other tracks at most once.
* The opening board is not already solved, feeds no Devourer, and the opening light wakes no seal.
* The stored solution is legal tap by tap, wins exactly on its last tap, lights every crystal, leaves the board recorded
  (mirrors, cannon aims, floe places and cluster turns) and its light runs in no loop.
* Par equals the length of the shortest solution found by exhaustive search.
* 3, 2, 1 and 0 shards are each reached by a legitimate tap sequence.

## Levels

| ID | Level | Title | Modifiers | Board | Cannons | Verified solution | Taps | 3 shards | 2 shards | 1 shard | Proven wins (3/2/1) | Can be lost | Result |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

Tap ids: \`e\` cannons, \`m\` path mirrors, \`d\` spare mirrors, \`f\` ice floes, \`t\` rootbound totems. Verification took ${Math.round((Date.now() - started) / 1000)} s.
`;
mkdirSync(join(__dirname, '..', 'docs'), { recursive: true });
writeFileSync(join(__dirname, '..', 'docs', 'LEVEL_REPORT.md'), doc);
console.log(`${passed}/${levels.length} levels pass`);
if (passed !== levels.length) process.exit(1);
